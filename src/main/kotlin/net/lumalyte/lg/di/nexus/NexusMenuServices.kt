/** Bean names follow NexusGuildCoreBindings' `guildSingleton` convention (lower-camel simple type name). */
private inline fun <reified T : Any> NexusContext.optionalMenuBean(name: String): T? =
    if (containsBean(name)) getBean(name) as T else null
